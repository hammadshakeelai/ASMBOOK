const fs = require('fs');
const lines = [];
lines.push('');
lines.push('  resetMachine(clearBps = true) {');
lines.push('    this.cpu = new CPU();');
lines.push('    this.cpu.setMem(0, 0, 8);');
lines.push('    this.ex = new Executor();');
lines.push('    if (this.parsed) { this.ex.load(this.parsed.instrs, { base: this.cellBase }); this.ex.bind(this.cpu); }');
lines.push('    if (clearBps) { this.bpSource.clear(); this.breakpoints.clear(); }');
lines.push('    else this.resyncBreakpoints();');
lines.push('    this.needsRestart = false;');
lines.push('  }');
lines.push('');
lines.push('  step() {');
lines.push('    if (!this.built) return this.emptyResult(\'error\', \'No program built yet\');');
lines.push('    if (this.needsRestart) return this.emptyResult(\'restart-needed\', \'Restart needed\');');
lines.push('    const ip = this.cpu.ip;');
lines.push('    if (ip >= this.parsed.instrs.length) return this.emptyResult(\'end\', \'At end of program\');');
lines.push('    const before = this.snapshotRegs();');
lines.push('    this.cpu.intOutput = () => {};');
lines.push('    this.ex.step();');
lines.push('    const after = this.snapshotRegs();');
lines.push('    const regDiff = diffRegs(before, after);');
lines.push('    const instr = this.parsed.instrs[ip];');
lines.push('    const cellId = instr ? this.lineOwner[instr.lineNum - 1] ?? null : null;');
lines.push('    const expectResults = cellId ? this.evalExpects(cellId) : [];');
lines.push('    return { reason: this.cpu.halted ? \'halted\' : \'cell-end\', steps: 1, output: \'\', regDiff,');
lines.push('      halted: !!this.cpu.halted, expectResults, allPassed: expectResults.every(r => r.passed) };');
lines.push('  }');
lines.push('');
lines.push('  continueRun() {');
lines.push('    if (!this.built) return this.emptyResult(\'error\', \'No program built yet\');');
lines.push('    if (this.needsRestart) return this.emptyResult(\'restart-needed\', \'Restart needed\');');
lines.push('    const before = this.snapshotRegs();');
lines.push('    const outBuf = [];');
lines.push('    this.cpu.intOutput = (s) => outBuf.push(s);');
lines.push('    let steps = 0;');
lines.push('    const CAP = 200000;');
lines.push('    let reason = \'end\';');
lines.push('    while (steps < CAP) {');
lines.push('      const ip = this.cpu.ip;');
lines.push('      if (ip >= this.parsed.instrs.length) { reason = \'end\'; break; }');
lines.push('      if (this.breakpoints.has(ip)) { reason = \'breakpoint\'; break; }');
lines.push('      this.ex.step();');
lines.push('      steps++;');
lines.push('      if (this.cpu.halted) { reason = \'halted\'; break; }');
lines.push('    }');
lines.push('    if (steps >= CAP) reason = \'cap\';');
lines.push('    const after = this.snapshotRegs();');
lines.push('    const regDiff = diffRegs(before, after);');
lines.push('    const ip = Math.min(this.cpu.ip, this.parsed.instrs.length - 1);');
lines.push('    const cellId = this.parsed.instrs[ip] ? this.lineOwner[this.parsed.instrs[ip].lineNum - 1] ?? null : null;');
lines.push('    const expectResults = cellId ? this.evalExpects(cellId) : [];');
lines.push('    return { reason, steps, output: outBuf.join(\'\'), regDiff, halted: !!this.cpu.halted,');
lines.push('      expectResults, allPassed: expectResults.every(r => r.passed) };');
lines.push('  }');
