const fs = require('fs');
const lines = [];
lines.push('');
lines.push('  runCell(cellId) { return this.run(cellId); }');
lines.push('');
lines.push('  runUpTo(cellId) {');
lines.push('    this.resetMachine(false);');
lines.push('    return this.run(cellId);');
lines.push('  }');
lines.push('');
lines.push('  run(targetCellId) {');
lines.push('    if (!this.built) return this.emptyResult(\'error\', \'No program built yet\');');
lines.push('    if (this.needsRestart) return this.emptyResult(\'restart-needed\', \'The machine needs a restart\');');
lines.push('    const targetIdx = this.cells.findIndex(c => c.id === targetCellId && c.kind === \'code\');');
lines.push('    if (targetIdx < 0) return this.emptyResult(\'error\', \'No such code cell\');');
lines.push('    const before = this.snapshotRegs();');
lines.push('    const outBuf = [];');
lines.push('    this.cpu.intOutput = (s) => outBuf.push(s);');
lines.push('    const cellEndLine = targetIdx + 1 < this.starts.length ? this.starts[targetIdx + 1] - 1 : Infinity;');
lines.push('    let steps = 0;');
lines.push('    const CAP = 200000;');
lines.push('    let reason = \'cell-end\';');
lines.push('    while (steps < CAP) {');
lines.push('      const ip = this.cpu.ip;');
lines.push('      if (ip >= this.parsed.instrs.length) { reason = \'end\'; break; }');
lines.push('      const curLine = this.parsed.instrs[ip].lineNum;');
lines.push('      if (curLine > cellEndLine) { reason = \'left-cell\'; break; }');
lines.push('      if (this.breakpoints.has(ip)) { reason = \'breakpoint\'; break; }');
lines.push('      this.ex.step();');
lines.push('      steps++;');
lines.push('      if (this.cpu.halted) { reason = \'halted\'; break; }');
lines.push('    }');
lines.push('    if (steps >= CAP) reason = \'cap\';');
lines.push('    const after = this.snapshotRegs();');
lines.push('    const regDiff = diffRegs(before, after);');
lines.push('    const output = outBuf.join(\'\');');
lines.push('    const expectResults = this.evalExpects(targetCellId);');
lines.push('    const result = { reason, steps, output, regDiff, halted: !!this.cpu.halted,');
lines.push('      expectResults, allPassed: expectResults.every(r => r.passed) };');
lines.push('    this.outputs.set(targetCellId, { text: output, regDiff, steps, reason, stale: false,');
lines.push('      expectResults, allPassed: result.allPassed });');
lines.push('    return result;');
lines.push('  }');
