const fs = require('fs');
const lines = [];
lines.push('  setCells(cells) {');
lines.push('    const r = this.rebuild(cells);');
lines.push('    this.needsRestart = r.needsRestart;');
lines.push('    return r;');
lines.push('  }');
lines.push('');
lines.push('  rebuild(cells) {');
lines.push('    this.cells = cells;');
lines.push('    this.outputs.clear();');
lines.push('    this.expectsByCell.clear();');
lines.push('    const codeCells = cells.filter(c => c.kind === \'code\');');
lines.push('    const parts = [];');
lines.push('    this.starts = [];');
lines.push('    this.lineOwner = [];');
lines.push('    for (const c of codeCells) {');
lines.push('      this.starts.push(parts.length + 1);');
lines.push('      for (const ln of c.source.split(\'\\n\')) { this.lineOwner.push(c.id); parts.push(ln); }');
lines.push('    }');
lines.push('    this.parsed = new Parser().parse(parts.join(\'\\n\'));');
lines.push('    for (const c of codeCells) {');
lines.push('      this.expectsByCell.set(c.id, parseExpects(c.source));');
lines.push('    }');
lines.push('    this.built = true;');
lines.push('    const prevIP = this.cpu.ip;');
lines.push('    this.ex = new Executor();');
lines.push('    this.ex.load(this.parsed.instrs, { base: this.cellBase });');
lines.push('    this.cpu = new CPU();');
lines.push('    this.cpu.setMem(0, 0, 8);');
lines.push('    this.ex.bind(this.cpu);');
lines.push('    this.resyncBreakpoints();');
lines.push('    if (prevIP < this.parsed.instrs.length && this.parsed.instrs[prevIP]) {');
lines.push('      this.cpu.ip = prevIP;');
lines.push('      return { needsRestart: false };');
lines.push('    }');
lines.push('    return { needsRestart: true };');
lines.push('  }');
